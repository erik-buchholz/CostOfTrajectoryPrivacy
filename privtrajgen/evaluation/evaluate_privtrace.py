#!/usr/bin/env python3
"""Separate evaluation script for PrivTrace."""
import argparse
import logging
import os
from dataclasses import asdict
from pathlib import Path
from pprint import pprint
from timeit import default_timer as timer
from typing import Any, Union, List

import numpy as np

from privtrajgen.config import EVALUATION_TRAJECTORY_NUM, PRIVTRACE_OUTPUT_DIR, LOG_DIR
from privtrajgen.datasets import dataset_bounding_boxes, denormalise_by_dataset
from privtrajgen.datasets.privtrace_adapter import transform_data_from_privtrace_to_difftraj
from privtrajgen.metrics import compute_all_metrics, save_metrics
from privtrajgen.utils import count_outside_bbox, set_random_seed, time_to_str, configure_root_loger
from .config import PrivTraceConfig
from .config import privTrace_configs
from .factories import get_test_dataset

log = logging.getLogger()


def logc(header: str, *args: Any, column_width: int = 40, level: int = logging.INFO) -> None:
    txt = f"{header:<{column_width}}" + "".join([str(arg) for arg in args])
    log.log(level, txt)


def get_argparser() -> argparse.ArgumentParser:
    """Create the argument parser for the evaluation scripts."""
    parser = argparse.ArgumentParser(description='Run the evaluation.')
    # Choose the configuration ID
    parser.add_argument('-c', '--config', type=str, choices=privTrace_configs.keys(),
                        help='The configuration to run.')
    # Choose the run ID
    parser.add_argument('-r', '--run', type=int, help='The run ID to start from.', default=None)
    # dry-run: Only print the configuration
    parser.add_argument('--dry-run', action='store_true', help='Only print the configuration.')
    return parser


def evaluate_privtrace_run(config: PrivTraceConfig, validation_run: int = 1) -> None:
    """Evaluate the model on the given dataset."""
    # Load real trajectories as baseline for the metrics
    real_dataset = get_test_dataset(config)

    # Select the evaluation size from the real dataset
    idx = np.random.choice(len(real_dataset), size=EVALUATION_TRAJECTORY_NUM, replace=False)
    real_dataset = real_dataset[idx]

    # Determine Path: f"{dataset}_e{epsilon:.1f}_{fold}_output.dat"
    fold = config.run_id - 1  # The run ID is 1-based, but the fold is 0-based
    name = f"{config.dataset.upper()}_e{config.epsilon:.1f}_{fold:02d}"
    if config.custom_K:
        name += "custom-K"
    if config.custom_Kappa:
        name += "custom-Kappa"
    name += "_output.dat"
    synthetic_data_path = Path(PRIVTRACE_OUTPUT_DIR) / name

    # Load the synthetic trajectories generated by the PrivTrace Submodule
    syn_dataset = transform_data_from_privtrace_to_difftraj(file_path=synthetic_data_path,
                                                            max_len=config.data.traj_length)
    log.info(f"Loaded synthetic dataset from {synthetic_data_path}.")

    # Check that both datasets have the same format (number of trajectories etc.)
    assert syn_dataset.shape == real_dataset.shape, \
        f"Mismatch between real dataset shape ({real_dataset.shape}) and synthetic dataset shape ({syn_dataset.shape})."

    # Reshape both datasets from (B, 2, L) to (B, L, 2)
    real_dataset = real_dataset.transpose(0, 2, 1)
    syn_dataset = syn_dataset.transpose(0, 2, 1)

    # Assert shape of both should be (EVALUATION_TRAJECTORY_NUM, config.data.traj_length, 2)
    assert syn_dataset.shape == (EVALUATION_TRAJECTORY_NUM, config.data.traj_length, 2)
    assert real_dataset.shape == (EVALUATION_TRAJECTORY_NUM, config.data.traj_length, 2)
    log.debug("Datasets have the expected shape.")

    # The synthetic dataset is already denormalised, as PrivTrace works on un-normalised data
    # --> Denormalise the real dataset
    # 1) Count how many values are outside the expected range [-1, 1]
    real_outside = np.sum(np.abs(real_dataset) > 1)
    # 2) The real dataset should not have values outside [-1, 1].
    assert real_outside == 0, f"Real dataset has values outside [-1, 1]."
    # 3) Denormalise the datasets into geographical coordinates
    real_dataset = denormalise_by_dataset(real_dataset, config.dataset)

    # Retrieve the dataset-specific bounding box
    bounding_box = dataset_bounding_boxes[config.dataset]

    # Check how many values are outside the bounding box
    # Assume the last dimension is in (lon, lat) order, and bounding box is dict (lon|lat)_(min|max) -> value
    real_outside = count_outside_bbox(real_dataset, bounding_box)
    # The synthetic data does not operate on a fixed BBOX, so better add some epsilon.
    eps = 0  # Has to be adapted once we have more knowledge about the data
    relaxed_bbox = {
        "lon_min": bounding_box["lon_min"] - eps,
        "lon_max": bounding_box["lon_max"] + eps,
        "lat_min": bounding_box["lat_min"] - eps,
        "lat_max": bounding_box["lat_max"] + eps,
    }
    syn_outside = count_outside_bbox(syn_dataset, relaxed_bbox)
    assert real_outside == 0, f"Real dataset has {real_outside} values outside the denormalised bounding box."
    assert syn_outside == 0, f"Synthetic dataset has {syn_outside} values outside the denormalised bounding box."
    log.debug("Datasets are inside the bounding box.")

    # Assert run ID has been added to seed
    assert config.seed == 42 + config.run_id, f"Unexpected seed value: {config.seed}."

    # Compute the metrics
    results = compute_all_metrics(
        trajectory_dataset1=real_dataset,
        trajectory_dataset2=syn_dataset,
        lon_first=True,
        geographical_coordinates=True,
        are_matched=False,  # PrivTrace does not match the trajectories
        bbox=relaxed_bbox,
        random_seed=config.seed,
    )

    # Save metrics to file
    filename = f"{config.name}_{validation_run:02d}"
    save_metrics(
        results=results,
        filename=filename,
        metadata=asdict(config),
        per_traj_metrics=True,
    )


def evaluate_privtrace(config: PrivTraceConfig) -> None:
    """Validate_model_subprocess equivalent."""
    # Log the configuration
    log.info(f"Configuration: {config}")

    # Pretty print the config
    pprint(asdict(config))

    # Set the random seeds
    set_random_seed(config.seed)

    # Evaluate the model
    for run in range(1, config.validation.runs + 1):
        start = timer()
        evaluate_privtrace_run(config, validation_run=run)
        log.info(f"Evaluation terminated in {time_to_str(timer() - start)}")


def run_privtrace_eval(configs: Union[PrivTraceConfig, List[PrivTraceConfig]],
                       run: int | None = None,
                       dry_run: bool = False,
                       ) -> None:
    """Equivalent operation to 'factories.execute'."""

    # Make sure configs is a list
    if not isinstance(configs, list):
        configs = [configs]

    for config in configs:
        if dry_run:
            pprint(asdict(config))
            continue
        # Override the run ID - allows to resume from a specific run
        if run is not None:
            start_id = run
        else:
            start_id = config.run_id
        log.info(f"Starting run ID {start_id}.")
        for run in range(start_id, config.num_runs + start_id):
            # Update the run id & seed
            config.run_id = run
            config.seed = config.seed + run
            # Start timer
            start_time = timer()
            evaluate_privtrace(config)
            # Log the time
            runtime = timer() - start_time  # in seconds
            log.info(f"Process terminated in {time_to_str(runtime)}")


if __name__ == '__main__':
    # Configure the logger
    configure_root_loger(logging.DEBUG, os.path.join(LOG_DIR, f'privTrace_eval.log'))
    # Parse the arguments
    args = get_argparser().parse_args()
    configs = privTrace_configs[args.config]
    # Call the main function
    run_privtrace_eval(configs=configs, run=args.run, dry_run=args.dry_run)
